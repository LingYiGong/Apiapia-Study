    /**
     * 为单词获取所有匹配的例句列表
     */
    function getAllSentencesForWord(item, sentenceList = []) {
        if (!item) return [];
        const word = (item.word || '').trim();
        const kana = (item.kana || '').trim();
        const meaning = (item.meaning || '').trim();

        const cleanWord = word.replace(/^[~～]/, '').trim();
        const cleanKana = kana.replace(/^[~～]/, '').trim();

        const results = [];
        const seenJapanese = new Set();

        function addSentence(s) {
            if (!s || !s.japanese) return;
            const key = s.japanese.trim();
            if (!seenJapanese.has(key)) {
                seenJapanese.add(key);
                results.push({
                    category: s.category || 'work',
                    ...s
                });
            }
        }

        // 1. 优先查阅高品质定制例句字典 (Curated Work & Life Sentences)
        if (CURATED_SENTENCES[word]) {
            addSentence({ ...CURATED_SENTENCES[word], source: 'curated' });
        }
        if (cleanWord && CURATED_SENTENCES[cleanWord]) {
            addSentence({ ...CURATED_SENTENCES[cleanWord], source: 'curated' });
        }
        if (kana && CURATED_SENTENCES[kana]) {
            addSentence({ ...CURATED_SENTENCES[kana], source: 'curated' });
        }

        // 2. 查阅内置例句库 (sentenceList)
        if (sentenceList && sentenceList.length > 0) {
            // (1) 精确匹配 words 标签数组
            const exactMatches = sentenceList.filter(s => 
                s.words && Array.isArray(s.words) && (
                    s.words.includes(word) ||
                    (cleanWord && s.words.includes(cleanWord)) ||
                    s.words.includes(kana) ||
                    (cleanKana && s.words.includes(cleanKana))
                )
            );
            exactMatches.sort((a, b) => (a.japanese ? a.japanese.length : 999) - (b.japanese ? b.japanese.length : 999));
            exactMatches.slice(0, 3).forEach(s => {
                addSentence({
                    category: detectCategory(s.japanese, s.chinese),
                    japanese: s.japanese,
                    kana: s.kana,
                    chinese: s.chinese,
                    source: 'library'
                });
            });

            // (2) 字符串子串包含匹配
            // 严禁单字、接尾词(~)、虚词参与宽泛子串匹配；且要求匹配处不在复合词汉字内部
            const isSingleChar = cleanWord.length <= 1;
            const isAffix = word.startsWith('～') || word.startsWith('~');
            if (results.length < 3 && !isSingleChar && !isAffix && cleanWord.length >= 2) {
                const subMatches = sentenceList.filter(s => {
                    if (!s.japanese || !s.japanese.includes(cleanWord)) return false;
                    if (s.words && s.words.includes(cleanWord)) return false;
                    
                    // 检查前后汉字边界，防止'釣り'匹配'お釣り'，'切る'匹配'切符'等
                    const idx = s.japanese.indexOf(cleanWord);
                    if (idx > 0) {
                        const prevChar = s.japanese[idx - 1];
                        if (/[\u4e00-\u9faf]/.test(prevChar) || prevChar === 'お' || prevChar === 'ご') {
                            return false;
                        }
                    }
                    if (idx + cleanWord.length < s.japanese.length) {
                        const nextChar = s.japanese[idx + cleanWord.length];
                        if (/[\u4e00-\u9faf]/.test(nextChar)) {
                            return false;
                        }
                    }
                    return true;
                });
                subMatches.sort((a, b) => (a.japanese.length - b.japanese.length));
                subMatches.slice(0, 2).forEach(s => {
                    addSentence({
                        category: detectCategory(s.japanese, s.chinese),
                        japanese: s.japanese,
                        kana: s.kana,
                        chinese: s.chinese,
                        source: 'library_sub'
                    });
                });
            }
        }

        // 3. 职场与生活真实语法规则生成兜底例句
        const ruleSentence = generateRuleSentence(word, kana, meaning, cleanWord, cleanKana);
        if (ruleSentence) {
            if (results.length === 0) {
                addSentence(ruleSentence);
            } else if (results.length < 2 && !['general_rule'].includes(ruleSentence.source)) {
                addSentence(ruleSentence);
            }
        }

        return results;
    }

    /**
     * 判断句子是职场还是生活类别
     */
    function detectCategory(japanese = '', chinese = '') {
        const text = japanese + chinese;
        if (/仕事|会社|業務|会議|資料|プロジェクト|開発|システム|エンジニア|仕様|確認|相談|報告|残業|有給|出張|面接|履歴書|提出|顧客|クライアント|担当|不具合|バグ|転職/i.test(text)) {
            return 'work';
        }
        return 'life';
    }

